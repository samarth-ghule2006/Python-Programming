print(a)        # Subtraction Assignment Operator

a *= b
print(a)        # Multiplication Assignment Operator

a /= b
print(a)        # Division Assignment Operator

a %= b
print(a)        # Modulus Assignment Operator

a //= b
print(a)        # Floor Division Assignment Operator

a **= b
print(a)        # Exponentiation Assignment Operator

a &= b
print(a)        # Bitwise AND Assignment Operator

a |= b
print(a)        # Bitwise OR Assignment Operator

a ^= b
print(a)        # Bitwise XOR Assignment Operator 

