# Creating a tuple
tup = ()
print(tup)

# Using String
tup = ('Geeks', 'for')
print(tup)

# Using built-in function
tup = tuple('Geeks')
print(tup)

# Accesing Elements
tup = tuple("Geeks")
print(tup[0])
print(tup[1:4])
print(tup[:3])

# Slicing of tuple
tup = tuple('GEEKSFORGEEKS')
print(tup[1:])
print(tup[::-1])
print(tup[4:9])

# Deleting a tuple
a = (0, 1, 2, 3, 4)
del tup
print(tup)